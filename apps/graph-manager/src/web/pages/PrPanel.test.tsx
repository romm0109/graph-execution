// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import { afterEach, describe, expect, it, vi } from "vitest";
import { ToastProvider } from "../ui/toast";
import { PR_POLL_MS, PrPanel, type PrJob } from "./PrPanel";

afterEach(() => {
  cleanup();
  vi.useRealTimers();
  vi.unstubAllGlobals();
});

const json = (status: number, body: unknown) => new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });
const flush = () => act(async () => vi.advanceTimersByTimeAsync(0));

const GH = "github~octo~hello";
const GL = "gitlab~grp~sub~proj";
const BODY = "- [x] 1 Say hello\n\nGenerated by graph-execution run r1.";
const SUGGESTED = { branch: "gm/r1", title: "Hello feature", body: BODY, base: "main", bases: ["main", "develop"] };

function renderPanel(ws = GH, { status = "applied", hash = "" }: { status?: string; hash?: string } = {}) {
  return render(
    <MemoryRouter initialEntries={[`/runs/${ws}/r1${hash}`]}>
      <ToastProvider>
        <PrPanel ws={ws} runId="r1" status={status} fullPath="/ws/github/octo/hello" />
      </ToastProvider>
    </MemoryRouter>,
  );
}

const job = (states: [string, string?][], extra: Partial<PrJob> = {}): PrJob => ({
  id: "j1",
  status: "running",
  steps: (["checkout", "commit", "push", "create"] as const).map((name, i) => ({
    name,
    state: (states[i]?.[0] ?? "pending") as PrJob["steps"][number]["state"],
    ...(states[i]?.[1] ? { detail: states[i]![1] } : {}),
  })),
  base: "main",
  branch: "gm/r1",
  startedAt: "2026-11-06T10:00:00.000Z",
  ...extra,
});

describe("PrPanel", () => {
  it("explains a run that has not landed, with the fix-it line", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => json(200, { eligible: false, reason: "the run has not landed (status failed)" })));
    renderPanel(GH, { status: "failed" });
    expect((await screen.findByTestId("pr-reason")).textContent).toBe("Not available: the run has not landed (status failed).");
    expect(screen.getByTestId("pr-fix-hint").textContent).toBe(
      "Fix it from a terminal in /ws/github/octo/hello and start a new run. Create PR shows up here once a run lands.",
    );
    expect(screen.getByText("GITHUB")).toBeTruthy();
    expect(screen.queryByTestId("pr-form")).toBeNull();
  });

  it("explains a workspace without changes, without the fix-it line", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => json(200, { eligible: false, reason: "no uncommitted changes in the workspace" })));
    renderPanel();
    expect((await screen.findByTestId("pr-reason")).textContent).toBe("Not available: no uncommitted changes in the workspace.");
    expect(screen.queryByTestId("pr-fix-hint")).toBeNull();
  });

  it("prefills the form with the suggestion, including the body text and the bases", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => json(200, { eligible: true, suggested: SUGGESTED })));
    renderPanel();
    expect(((await screen.findByTestId("pr-branch")) as HTMLInputElement).value).toBe("gm/r1");
    expect((screen.getByTestId("pr-title") as HTMLInputElement).value).toBe("Hello feature");
    const body = screen.getByTestId("pr-body") as HTMLTextAreaElement;
    expect(body.value).toBe(BODY);
    expect(body.value).not.toContain("[object Object]");
    expect(body.rows).toBe(8);
    const base = screen.getByTestId("pr-base") as HTMLSelectElement;
    expect(base.value).toBe("main");
    expect(Array.from(base.options).map((o) => o.value)).toEqual(["main", "develop"]);
    expect(screen.getByText("from the spec’s heading")).toBeTruthy();
    expect(screen.getByTestId("pr-submit").textContent).toBe("Create PR");

    fireEvent.change(screen.getByTestId("pr-title"), { target: { value: "Edited" } });
    fireEvent.click(screen.getByTestId("pr-cancel"));
    expect((screen.getByTestId("pr-title") as HTMLInputElement).value).toBe("Hello feature");
  });

  it("offers Create MR on GitLab", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => json(200, { eligible: true, suggested: SUGGESTED })));
    renderPanel(GL);
    expect((await screen.findByTestId("pr-submit")).textContent).toBe("Create MR");
    expect(screen.getByText("GITLAB")).toBeTruthy();
  });

  it("posts the form, shows the steps while the job runs, polls every second, then shows the PR and a toast", async () => {
    vi.useFakeTimers();
    const polls: PrJob[] = [
      job([["done", "gm/r1"], ["done", "1 file · “Edited”"], ["running", "origin · 62%"]]),
      job([["done", "gm/r1"], ["done", "1 file · “Edited”"], ["done", "origin"], ["done", "GitHub PR → main"]], {
        status: "done",
        pr: { url: "http://forge/pull/1", number: 1, branch: "gm/r1" },
      }),
    ];
    let gets = 0;
    const fetchMock = vi.fn(async (url: string, init?: RequestInit) => {
      if (init?.method === "POST") return json(202, { job: job([["running", "gm/r1"]]) });
      if (gets++ === 0) return json(200, { eligible: true, suggested: SUGGESTED });
      const j = polls.shift()!;
      return j.status === "done"
        ? json(200, { pr: { ...j.pr, base: "main" }, eligible: false, job: j })
        : json(200, { eligible: false, reason: "no uncommitted changes in the workspace", job: j });
    });
    vi.stubGlobal("fetch", fetchMock);
    const open = vi.fn();
    vi.stubGlobal("open", open);
    renderPanel();
    await flush();
    fireEvent.change(screen.getByTestId("pr-title"), { target: { value: "Edited" } });
    fireEvent.click(screen.getByTestId("pr-submit"));
    await flush();

    const sent = fetchMock.mock.calls.find(([, i]) => i?.method === "POST");
    expect(sent?.[0]).toBe(`/api/runs/${GH}/r1/pr`);
    expect(JSON.parse(String(sent?.[1]?.body))).toEqual({ branch: "gm/r1", base: "main", title: "Edited", body: BODY });
    expect(screen.getByTestId("pr-step-checkout").dataset.state).toBe("running");
    expect(screen.getByTestId("pr-submit").textContent).toBe("Creating…");
    expect((screen.getByTestId("pr-submit") as HTMLButtonElement).disabled).toBe(true);
    expect((screen.getByTestId("pr-title") as HTMLInputElement).readOnly).toBe(true);
    expect((screen.getByTestId("pr-base") as HTMLSelectElement).disabled).toBe(true);

    await act(async () => vi.advanceTimersByTimeAsync(PR_POLL_MS));
    // The form stays (read-only) even though the server now says the workspace has no changes.
    expect(screen.getByTestId("pr-step-push").dataset.state).toBe("running");
    expect(screen.getByTestId("pr-step-push").textContent).toContain("origin · 62%");
    expect(screen.getByTestId("pr-step-push").querySelector("[data-glyph]")?.getAttribute("data-glyph")).toBe("pulse");
    expect(screen.getByTestId("pr-step-create").querySelector("[data-glyph]")?.getAttribute("data-glyph")).toBe("dashed");
    expect(screen.getByTestId("pr-step-checkout").querySelector("[data-glyph]")?.getAttribute("data-glyph")).toBe("dot");
    expect((screen.getByTestId("pr-title") as HTMLInputElement).value).toBe("Edited");

    await act(async () => vi.advanceTimersByTimeAsync(PR_POLL_MS));
    const link = screen.getByTestId("pr-link");
    expect(link.textContent).toBe("Pull request #1 ↗");
    expect(link.getAttribute("href")).toBe("http://forge/pull/1");
    expect(link.getAttribute("target")).toBe("_blank");
    expect(screen.getByTestId("pr-exists").textContent).toContain("gm/r1 → main");
    const toast = screen.getByRole("status");
    expect(toast.textContent).toContain("Opened PR #1");
    fireEvent.click(screen.getByText("Open"));
    expect(open).toHaveBeenCalledWith("http://forge/pull/1", "_blank", "noopener");

    // No more polls once the job is done.
    const calls = fetchMock.mock.calls.length;
    await act(async () => vi.advanceTimersByTimeAsync(PR_POLL_MS * 3));
    expect(fetchMock.mock.calls.length).toBe(calls);
  });

  it("shows a failed job with the failed step and its error, and enables the form again", async () => {
    const failed = job([["done", "gm/r1"], ["done", "1 file"], ["failed", "origin"]], { status: "failed", failedStep: "push", error: "push failed: denied" });
    vi.stubGlobal("fetch", vi.fn(async () => json(200, { eligible: true, suggested: SUGGESTED, job: failed })));
    renderPanel();
    expect((await screen.findByTestId("pr-job-error")).textContent).toBe("push failed: denied");
    expect(screen.getByTestId("pr-step-push").dataset.state).toBe("failed");
    expect(screen.getByTestId("pr-step-push").querySelector("[data-glyph]")?.getAttribute("data-glyph")).toBe("diamond");
    expect((screen.getByTestId("pr-submit") as HTMLButtonElement).disabled).toBe(false);
    expect((screen.getByTestId("pr-title") as HTMLInputElement).readOnly).toBe(false);
  });

  it("shows a POST error under the form", async () => {
    vi.stubGlobal(
      "fetch",
      vi.fn(async (_url: string, init?: RequestInit) =>
        init?.method === "POST" ? json(409, { error: "branch gm/r1 already exists" }) : json(200, { eligible: true, suggested: SUGGESTED }),
      ),
    );
    renderPanel();
    fireEvent.click(await screen.findByTestId("pr-submit"));
    expect((await screen.findByTestId("pr-error")).textContent).toBe("branch gm/r1 already exists");
  });

  it("shows an existing merge request", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => json(200, { pr: { url: "http://forge/mr/17", number: 17, branch: "gm/r1", base: "develop" }, eligible: false })));
    renderPanel(GL);
    expect((await screen.findByTestId("pr-link")).textContent).toBe("Merge request !17 ↗");
    expect(screen.getByTestId("pr-exists").textContent).toContain("gm/r1 → develop");
  });

  it("focuses the Title field when the URL ends in #pr", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => json(200, { eligible: true, suggested: SUGGESTED })));
    const scroll = vi.fn();
    const original = Element.prototype.scrollIntoView;
    Element.prototype.scrollIntoView = scroll;
    try {
      renderPanel(GH, { hash: "#pr" });
      const title = await screen.findByTestId("pr-title");
      await vi.waitFor(() => expect(document.activeElement).toBe(title));
      expect(scroll).toHaveBeenCalled();
    } finally {
      Element.prototype.scrollIntoView = original;
    }
  });
});

describe("PrPanel of a project run", () => {
  const HOME = "project~billing";
  const failedJob = {
    id: "pj1",
    status: "failed",
    startedAt: "2026-11-13T12:00:00.000Z",
    repos: [
      { name: "api", status: "done", steps: [], pr: { url: "https://gh/acme/api/pull/4", number: 4, branch: "gm/r1" } },
      { name: "web", status: "failed", steps: [], error: "push failed: repository not found" },
    ],
    link: { state: "pending" },
    error: "web: push failed: repository not found",
  };

  function renderProject() {
    return render(
      <MemoryRouter initialEntries={[`/runs/${HOME}/r1`]}>
        <ToastProvider>
          <PrPanel ws={HOME} runId="r1" status="applied" project />
        </ToastProvider>
      </MemoryRouter>,
    );
  }

  it("renders a row per repo with the open PR, the failed repo's error and Retry", async () => {
    const fetchMock = vi.fn(async (_url: string, init?: RequestInit) => {
      if (init?.method === "POST") return json(202, { job: { ...failedJob, status: "running" } });
      return json(200, {
        project: true,
        eligible: true,
        repos: [
          { name: "api", workspaceId: "github~acme~api", fullPath: "acme/api", changed: false, pr: { url: "https://gh/acme/api/pull/4", number: 4, branch: "gm/r1" } },
          { name: "web", workspaceId: "github~acme~web", fullPath: "acme/web", changed: true, error: "push failed: repository not found" },
        ],
        job: failedJob,
      });
    });
    vi.stubGlobal("fetch", fetchMock);
    renderProject();
    expect((await screen.findByTestId("pr-project-repos")).textContent).toContain("acme/api");
    const api = screen.getByTestId("pr-repo-api");
    expect(api.textContent).toContain("PR #4 ↗");
    expect(api.querySelector("a")?.getAttribute("href")).toBe("https://gh/acme/api/pull/4");
    expect(screen.getByTestId("pr-repo-web").textContent).toContain("acme/web");
    expect(screen.getByTestId("pr-repo-error-web").textContent).toBe("push failed: repository not found");
    expect(screen.queryByTestId("pr-repo-error-api")).toBeNull();
    expect(screen.getByText("GITHUB")).toBeTruthy();
    const button = screen.getByTestId("pr-submit") as HTMLButtonElement;
    expect(button.textContent).toBe("Retry");
    expect(button.disabled).toBe(false);
    fireEvent.click(button);
    await screen.findByText("Creating…");
    expect(fetchMock.mock.calls.some(([u, i]) => u === `/api/runs/${encodeURIComponent(HOME)}/r1/pr` && i?.method === "POST")).toBe(true);
  });

  it("offers Create MRs on GitLab and shows the reason when not eligible", async () => {
    vi.stubGlobal(
      "fetch",
      vi.fn(async () =>
        json(200, {
          project: true,
          eligible: true,
          repos: [{ name: "api", workspaceId: "gitlab~grp~api", fullPath: "grp/api", changed: true }],
        }),
      ),
    );
    renderProject();
    expect((await screen.findByTestId("pr-submit")).textContent).toBe("Create MRs");
    expect(screen.getByText("GITLAB")).toBeTruthy();
    cleanup();
    vi.stubGlobal("fetch", vi.fn(async () => json(200, { project: true, eligible: false, reason: "no repo has changes to open a PR from", repos: [] })));
    renderProject();
    expect((await screen.findByTestId("pr-reason")).textContent).toBe("Not available: no repo has changes to open a PR from.");
    expect(screen.queryByTestId("pr-submit")).toBeNull();
  });
});
